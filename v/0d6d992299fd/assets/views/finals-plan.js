const kst = (date, hhmm) => Date.parse(`${date}T${hhmm}:00+09:00`);

/** 칸 하나하나: { id, day, date, start, end, startMs, endMs, what, note } (시간 순) */
export function finalsBlocks() {
  const out = [];
  FINALS_DAYS.forEach((d, di) => d.rows.forEach(([start, end, what, note], ri) => {
    out.push({ id: `d${di + 1}-${ri + 1}`, day: di + 1, date: d.date, start, end, startMs: kst(d.date, start), endMs: kst(d.date, end), what, note });
  }));
  return out;
}

/** 안내 화면 일정표: [[날 제목, [['09:30 – 10:00', 할 일, 비고], …]], …] */
export function scheduleRows() {
  return FINALS_DAYS.map((d) => [d.label, d.rows.map(([start, end, what, note]) => [`${start} – ${end}`, what, note])]);
}

/**
 * 멘토 화면 순회 기록의 라운드(gas/MentorLog.js VISIT_ROUNDS 의 키)가 일정표의 어느 칸인지 — 칸 제목에 들어 있는 말로 찾는다.
 * 요청 방문은 1일차 저녁 자율 개발 칸(요청한 팀만 — 다른 때 방문해도 여기에 적는다).
 */
const ROUND_BLOCKS = {
  r1: ['멘토링 1라운드', '팀당 8분'],
  req: ['팀별 개발(자율)', '요청한 팀'],
  r2: ['멘토링 2라운드', '팀당 6분'],
  r3: ['멘토링 3라운드', '팀당 6분'],
};

/** { r1: { day, start, end, startMs, endMs, text: '1일차 16:00–18:00 · 팀당 8분' }, … } */
export function roundTimes() {
  const blocks = finalsBlocks();
  const out = {};
  Object.keys(ROUND_BLOCKS).forEach((k) => {
    const [word, per] = ROUND_BLOCKS[k];
    const b = blocks.find((x) => x.what.includes(word));
    out[k] = b ? { day: b.day, start: b.start, end: b.end, startMs: b.startMs, endMs: b.endMs, text: `${b.day}일차 ${b.start}–${b.end} · ${per}` } : null;
  });
  return out;
}

/** ms 시각에 열린 라운드의 키, 라운드 밖이면 ''(멘토 화면이 그 라운드를 먼저 연다) */
export function roundAt(ms) {
  const t = roundTimes();
  return Object.keys(t).find((k) => t[k] && t[k].startMs <= ms && ms < t[k].endMs) || '';
}

/** ms 시각의 지금 칸과 다음 칸. 칸 사이(밤 등)에는 now 가 null, 일정이 모두 끝나면 둘 다 null. */
export function nowNext(ms) {
  const blocks = finalsBlocks();
  const now = blocks.find((b) => b.startMs <= ms && ms < b.endMs) || null;
  const next = blocks.find((b) => b.startMs > ms) || null;
  return { now, next };
}

