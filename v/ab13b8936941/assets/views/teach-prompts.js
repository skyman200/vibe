export const itemOf = (id) => COPY_ITEMS.find((x) => x.id === id);

/** [복사] 단추로 클립보드에 넣을 글(복사 글 그대로). 없는 id 면 빈 글. */
export function copyOf(id) {
  const p = itemOf(id);
  return p ? p.text : '';
}
