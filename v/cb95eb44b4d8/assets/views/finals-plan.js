/** 공지 글의 자리 표시를 채운다. v: { deadline: '10. 30.(금) 13:30', readme: '프로젝트 개요, …' } */
export function fillCall(text, v) {
  return String(text).replace(/\{(deadline|readme|site)\}/g, (m, k) => (k === 'site' ? SITE_URL : v[k] || ''));
}

/** 공지마다 시각(ms)과 상태: later · soon(30분 안에 할 것) · now(할 때 — 그 시각부터 10분) · done(지남) */
export function callStates(ms) {
  return FINALS_CALLS.map((c) => {
    const at = Date.parse(`${c.at}:00+09:00`);
    const state = ms >= at + 10 * 60e3 ? 'done' : ms >= at ? 'now' : at - ms <= 30 * 60e3 ? 'soon' : 'later';
    return { ...c, atMs: at, state };
  });
}
